"""Write docs/SAMPLE_REPORT.md from the real output of every query."""
from __future__ import annotations

from pathlib import Path

from . import db


def write_report(db_path: Path, out: Path, rows_per_query: int = 12) -> Path:
    if not db_path.exists():
        raise SystemExit(f"No database at {db_path}. Run: python -m talentsql seed")
    conn = db.connect(db_path)
    meta = dict(conn.execute("SELECT key, value FROM meta").fetchall())
    counts = {t: conn.execute(f"SELECT COUNT(*) FROM {t}").fetchone()[0]
              for t in ("dim_employee", "dim_requisition", "fact_application", "fact_stage_event", "fact_offer")}
    parts = [
        "# Sample report", "",
        "Generated by `python -m talentsql report` from the real output of every query in `sql/queries/`.",
        "All data is synthetic (a fictional company).", "",
        f"- Seed: `{meta['seed']}`; as-of date: `{meta['as_of_date']}`",
        "- Rows: " + ", ".join(f"{n:,} {t}" for t, n in counts.items()), "",
    ]
    for q in db.load_queries():
        cols, rows = db.run_query(conn, q)
        parts += [f"## Query {q.number:02d}: {q.title}", "", f"**Question.** {q.question}", "",
                  f"**Technique.** {q.technique}", "", f"**File.** `sql/queries/{q.filename}`", "",
                  db.markdown_table(cols, rows, rows_per_query), ""]
    conn.close()
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(parts), encoding="utf-8")
    return out
